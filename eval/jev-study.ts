import { readFileSync, writeFileSync } from "node:fs"
import { RULE_FEATURE_IDS } from "@slop/features"
import { type Decision, type Score, Scorer } from "@slop/model"
import { RULE_NAMES } from "@slop/rules/names"
import { experimental_evaluate as evaluate } from "ai"

type Label = "human" | "machine" | "mixed"
type Row = { text: string; label: Label; split: string; domain: string }
type Call = { decision: Decision; top: Label; p: number }
type Result = {
  label: Label
  siteClass: string
  adversarial: boolean
  web: boolean
  local: Call
  jev: Call
  ms: number
  inputTokens: number
}
type System = "local" | "jev"
type CurvePoint = {
  threshold: number
  unsureRate: number
  accuracyDecided: number | null
}

const SAMPLE_SHARES = {
  human: 0.4,
  machine: 0.35,
  mixed: 0.15,
  adversarial: 0.1,
}
const SITE_CLASS_BY_DOMAIN: Record<string, string> = {
  reddit: "forum",
  reviews: "shop",
  wiki: "reference",
  news: "news",
  abstracts: "reference",
}
const RULE_LABELS = RULE_FEATURE_IDS.map((id) =>
  `${id} ${RULE_NAMES[id]?.name ?? ""}`.trim()
)
const round3 = (n: number) => Math.round(n * 1000) / 1000

function jevState(score: Score, siteClass: string) {
  return {
    rules: Object.fromEntries(
      RULE_LABELS.map((label, i) => [label, round3(score.vector[i])])
    ),
    model: {
      human: round3(score.probs.human),
      machine: round3(score.probs.machine),
      mixed: round3(score.probs.mixed),
    },
    context: {
      siteClass,
      hasByline: false,
      hasComments: false,
      words: score.words,
    },
  }
}

const JEV_QUESTIONS = {
  decision: {
    type: "choice",
    instructions:
      "State: stylometric rule scores (0 = absent, 1 = strong) and a small local model's calibrated class probabilities " +
      "for one paragraph of web text, plus page context. No text is included. Decide how the paragraph was produced. " +
      'Prefer "unsure" over a confident wrong call; formal human writing (news, encyclopedias, abstracts) often ' +
      "scores high on some rules.",
    criteria: {
      human: "written by a person without machine assistance",
      machine: "generated by a language model with little or no human editing",
      mixed:
        "a blend: human text polished by a model, or model text edited by a person",
      unsure: "the evidence does not support a call either way",
    },
  },
} as const

const CONCURRENCY = 16
const BOOTSTRAP_ROUNDS = 2000
const TARGET_ABSTENTION = 0.3
const MEANINGFUL_ECE_GAIN = 0.01

const readLocal = (path: string) => readFileSync(new URL(path, import.meta.url))

function seeded(seed: number): () => number {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}
const random = seeded(20260919)

async function loadScorer() {
  const manifestPath = "../packages/model/weights/manifest.json"
  const manifest = JSON.parse(readLocal(manifestPath).toString())
  const bin = readLocal("../packages/model/weights/model.bin")
  const weights = bin.buffer.slice(
    bin.byteOffset,
    bin.byteOffset + bin.byteLength
  )
  return Scorer.create(manifest, weights, { backend: "cpu" })
}

function shuffled<T>(items: T[]): T[] {
  const copy = [...items]
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1))
    ;[copy[i], copy[j]] = [copy[j], copy[i]]
  }
  return copy
}

function sampleRows(n: number, minWords: number): Row[] {
  const corpus: Row[] = readLocal("../training/data/corpus.jsonl")
    .toString()
    .trim()
    .split("\n")
    .map((line) => JSON.parse(line))
  const take = (keep: (r: Row) => boolean, share: number) =>
    shuffled(corpus.filter(keep)).slice(0, Math.round(n * share))
  const heldOut = (label: Label) => (r: Row) =>
    r.split === "test" && r.label === label

  const rows = [
    ...take(heldOut("human"), SAMPLE_SHARES.human),
    ...take(heldOut("machine"), SAMPLE_SHARES.machine),
    ...take(heldOut("mixed"), SAMPLE_SHARES.mixed),
    ...take((r) => r.split === "adv", SAMPLE_SHARES.adversarial),
    ...corpus.filter((r) => r.split === "web"),
  ]
  return rows.filter((r) => r.text.split(/\s+/).length >= minWords)
}

function topClass(probs: Partial<Record<string, number>>): Label {
  const classes: Label[] = ["human", "machine", "mixed"]
  return classes.reduce((a, b) => ((probs[b] ?? 0) > (probs[a] ?? 0) ? b : a))
}

async function askJev(scorer: Scorer, row: Row): Promise<Result> {
  const score = scorer.score(row.text)
  const siteClass = SITE_CLASS_BY_DOMAIN[row.domain] ?? "other"
  const started = Date.now()
  const { answers, usage } = await evaluate({
    model: "typesafe-ai/jev",
    state: jevState(score, siteClass),
    questions: JEV_QUESTIONS,
  })
  const { choice, probabilities } = answers.decision
  const jevProbs = probabilities ?? { [choice]: 1 }
  const jevTop = choice === "unsure" ? topClass(jevProbs) : choice
  const localTop = topClass(score.probs)

  return {
    label: row.label,
    siteClass,
    adversarial: row.split === "adv",
    web: row.split === "web",
    local: { decision: score.localDecision, top: localTop, p: score.localP },
    jev: { decision: choice, top: jevTop, p: jevProbs[jevTop] ?? 0 },
    ms: Date.now() - started,
    inputTokens: usage.inputTokens ?? 0,
  }
}

async function runAll(scorer: Scorer, rows: Row[]) {
  const results: (Result | undefined)[] = new Array(rows.length)
  const errors: string[] = []
  let next = 0
  const worker = async () => {
    for (let i = next++; i < rows.length; i = next++) {
      try {
        results[i] = await askJev(scorer, rows[i])
      } catch (error) {
        errors.push(String(error).slice(0, 200))
      }
    }
  }
  await Promise.all(Array.from({ length: CONCURRENCY }, worker))
  return { results: results.filter((r) => r !== undefined), errors }
}

function ece(results: Result[], system: System): number {
  let total = 0
  for (let bin = 0; bin < 10; bin++) {
    const inBin = results.filter((r) => {
      const p = r[system].p
      return p > bin / 10 && p <= (bin + 1) / 10
    })
    if (!inBin.length) continue
    const hits = inBin.filter((r) => r[system].decision === r.label).length
    const confidence = inBin.reduce((sum, r) => sum + r[system].p, 0)
    const gap = Math.abs(hits - confidence) / inBin.length
    total += (inBin.length / results.length) * gap
  }
  return total
}

function summarize(system: System, results: Result[]) {
  const decided = results.filter((r) => r[system].decision !== "unsure")
  const correct = decided.filter((r) => r[system].decision === r.label)
  const humans = results.filter((r) => r.label === "human")
  const falseMachine = humans.filter((r) => r[system].decision === "machine")
  const share = (d: Decision) =>
    results.filter((r) => r[system].decision === d).length / results.length

  return {
    n: results.length,
    unsureRate: share("unsure"),
    accuracyDecided: decided.length ? correct.length / decided.length : null,
    ece: ece(decided, system),
    falseMachineRateOnHuman: falseMachine.length / Math.max(humans.length, 1),
    outcomes: {
      human: share("human"),
      machine: share("machine"),
      mixed: share("mixed"),
      unsure: share("unsure"),
    },
  }
}

function accuracyAbove(system: System, threshold: number, results: Result[]) {
  const decided = results.filter((r) => r[system].p >= threshold)
  if (!decided.length) return null
  const correct = decided.filter((r) => r[system].top === r.label)
  return correct.length / decided.length
}

function curve(system: System, results: Result[]): CurvePoint[] {
  return Array.from({ length: 34 }, (_, i) => {
    const threshold = Number((0.33 + i * 0.02).toFixed(2))
    const decided = results.filter((r) => r[system].p >= threshold).length
    return {
      threshold,
      unsureRate: 1 - decided / results.length,
      accuracyDecided: accuracyAbove(system, threshold, results),
    }
  })
}

function closestTo(points: CurvePoint[], unsureRate: number): CurvePoint {
  const distance = (p: CurvePoint) => Math.abs(p.unsureRate - unsureRate)
  return points.reduce((best, p) => (distance(p) < distance(best) ? p : best))
}

function bootstrapGap(
  results: Result[],
  jevThreshold: number,
  localThreshold: number
): [number, number] {
  const pick = () => results[Math.floor(random() * results.length)]
  const gaps: number[] = []
  for (let round = 0; round < BOOTSTRAP_ROUNDS; round++) {
    const resample = results.map(pick)
    const jev = accuracyAbove("jev", jevThreshold, resample) ?? 0
    const local = accuracyAbove("local", localThreshold, resample) ?? 0
    gaps.push(jev - local)
  }
  gaps.sort((a, b) => a - b)
  const at = (q: number) => gaps[Math.floor(BOOTSTRAP_ROUNDS * q)]
  return [at(0.025), at(0.975)]
}

function compareBy(results: Result[], key: (r: Result) => string) {
  const groups = Map.groupBy(results, key)
  return Object.fromEntries(
    [...groups].map(([name, rows]) => [
      name,
      { local: summarize("local", rows), jev: summarize("jev", rows) },
    ])
  )
}

const percent = (x: number | null) => `${((x ?? 0) * 100).toFixed(1)}%`
const points = (x: number) => (x * 100).toFixed(1)
const percentile = (sorted: number[], q: number) =>
  sorted[Math.floor(sorted.length * q)]

async function main() {
  const n = Number(process.argv[2] ?? 600)
  const scorer = await loadScorer()
  const rows = sampleRows(n, scorer.manifest.minWords)
  const { results: all, errors } = await runAll(scorer, rows)
  const results = all.filter((r) => !r.web)
  const onWeb = all.filter((r) => r.web)

  const local = summarize("local", results)
  const jev = summarize("jev", results)
  const web = { local: summarize("local", onWeb), jev: summarize("jev", onWeb) }
  const curves = { local: curve("local", results), jev: curve("jev", results) }
  const atTarget = {
    local: closestTo(curves.local, TARGET_ABSTENTION),
    jev: closestTo(curves.jev, TARGET_ABSTENTION),
  }
  const gap = bootstrapGap(
    results,
    atTarget.jev.threshold,
    atTarget.local.threshold
  )

  const betterCalibrated = jev.ece < local.ece - MEANINGFUL_ECE_GAIN
  const moreAccurate = gap[0] > 0
  const decision = betterCalibrated || moreAccurate ? "keep" : "cut"

  const findings = [
    `ECE on decided paragraphs: Jev ${jev.ece.toFixed(3)}, local ${local.ece.toFixed(3)}.`,
    `Jev abstains on ${percent(jev.unsureRate)} of paragraphs, the local model on ${percent(local.unsureRate)}.`,
    `At ~${TARGET_ABSTENTION * 100}% abstention, accuracy is ${percent(atTarget.jev.accuracyDecided)} for Jev`,
    `vs ${percent(atTarget.local.accuracyDecided)} local`,
    `(95% CI of the gap: ${points(gap[0])} to ${points(gap[1])} points).`,
    `On ${web.jev.n} human paragraphs from sites kept out of training, Jev called`,
    `${percent(web.jev.falseMachineRateOnHuman)} machine-ish, the local model ${percent(web.local.falseMachineRateOnHuman)}.`,
  ].join(" ")
  const reason =
    decision === "keep"
      ? `Keep. ${findings}`
      : [
          "Cut. Jev is neither better calibrated nor, beyond noise, more accurate at equal abstention.",
          findings,
          "Neither the extension nor the site uses Jev. The study can be rerun on new weights, or against a new Jev.",
        ].join(" ")

  const latencies = all.map((r) => r.ms).sort((a, b) => a - b)
  const tokens = all.reduce((sum, r) => sum + r.inputTokens, 0)
  const study = {
    date: new Date().toISOString().slice(0, 10),
    modelVersion: scorer.manifest.version,
    n: results.length,
    failures: errors.length,
    note: "Held-out corpus paragraphs, plus a separate sample from the web check (2019 pages on sites kept out of training, all human). Site class is inferred from the source domain.",
    latencyMs: {
      p50: percentile(latencies, 0.5),
      p90: percentile(latencies, 0.9),
    },
    meanInputTokens: Math.round(tokens / all.length),
    local,
    jev,
    web,
    adversarial: compareBy(results, (r) =>
      r.adversarial ? "adversarial" : "held-out"
    ),
    byClass: compareBy(results, (r) => r.label),
    bySiteClass: compareBy(results, (r) => r.siteClass),
    curve: curves,
    operatingPoint: {
      targetAbstention: TARGET_ABSTENTION,
      ...atTarget,
      bootstrapGap95: gap,
    },
    decision,
    reason,
  }
  const out = new URL("jev-study.json", import.meta.url)
  writeFileSync(out, JSON.stringify(study, null, 1) + "\n")
  for (const error of errors.slice(0, 5)) console.error(error)
  console.log(reason)
}

await main()
